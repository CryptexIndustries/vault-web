// Regenerates the AutoFill extension's derived sources and test fixtures:
// the Swift protobuf types, the public suffix rules, the passphrase words,
// the decryption fixture, and the inbox fixture. Run with
// `pnpm --filter mobile autofill:generate` on macOS.
import { spawnSync } from "node:child_process";
import { readFileSync, writeFileSync } from "node:fs";
import { createRequire } from "node:module";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const targets = fileURLToPath(new URL("..", import.meta.url));
const mobile = join(targets, "..");
const vaultCore = join(mobile, "../packages/vault-core");
const generated = join(targets, "autofill/Core/Generated");

function run(command, args, cwd = targets) {
    const result = spawnSync(command, args, {
        cwd,
        stdio: ["ignore", "pipe", "inherit"],
        encoding: "utf8",
    });
    if (result.error) throw result.error;
    if (result.status !== 0)
        throw new Error(`${command} ${args.join(" ")} failed.`);
    return result.stdout.trim();
}

// protoc and protoc-gen-swift come from the swift-protobuf version pinned in
// Package.resolved, so the generator matches the runtime the extension links.
const swiftBuild = ["build", "-c", "release", "--package-path", targets];
run("swift", [...swiftBuild, "--product", "protoc"]);
run("swift", [...swiftBuild, "--product", "protoc-gen-swift"]);
const bin = run("swift", [...swiftBuild, "--show-bin-path"]);
run(join(bin, "protoc"), [
    `--plugin=protoc-gen-swift=${join(bin, "protoc-gen-swift")}`,
    `--proto_path=${join(vaultCore, "src/proto")}`,
    `--swift_out=${generated}`,
    "vault.proto",
]);

// The same rules, in punycode, that vault-core's psl package matches against.
const psl = dirname(
    dirname(createRequire(join(vaultCore, "package.json")).resolve("psl")),
);
const { version } = JSON.parse(readFileSync(join(psl, "package.json"), "utf8"));
const { default: rules } = await import(
    pathToFileURL(join(psl, "data/rules.js")).href
);
const punycode = createRequire(join(psl, "package.json"))(
    "punycode/punycode.js",
);
const lines = rules.map((rule) => {
    const prefix = rule.match(/^(?:\*\.|!)/)?.[0] ?? "";
    return prefix + punycode.toASCII(rule.slice(prefix.length));
});
writeFileSync(
    join(generated, "PublicSuffixRules.swift"),
    `// Generated by mobile/targets/scripts/generate.mjs from psl ${version}. DO NOT EDIT.\n\n` +
        `let publicSuffixRules = """\n${lines.join("\n")}\n"""\n`,
);

// The passphrase words the app's password generator draws from.
const bip39 = join(mobile, "node_modules/@scure/bip39");
const { version: bip39Version } = JSON.parse(
    readFileSync(join(bip39, "package.json"), "utf8"),
);
const { wordlist } = await import(
    pathToFileURL(join(bip39, "wordlists/english.js")).href
);
writeFileSync(
    join(generated, "Bip39EnglishWords.swift"),
    `// Generated by mobile/targets/scripts/generate.mjs from @scure/bip39 ${bip39Version}. DO NOT EDIT.\n\n` +
        `let bip39EnglishWords = """\n${wordlist.join("\n")}\n"""\n`,
);

// Jest runs the app's own vault and biometric enrollment code with storage mocks.
run(
    "pnpm",
    [
        "exec",
        "jest",
        "--config",
        "./jest.config.ts",
        "--testMatch",
        "**/targets/scripts/vault-fixture.gen.ts",
    ],
    mobile,
);
// The inbox fixture comes from the extension's own Swift, for the app's merge test.
const inbox = spawnSync(
    "swift",
    ["test", "--package-path", targets, "--filter", "writesTheInboxFixture"],
    {
        cwd: targets,
        stdio: ["ignore", "ignore", "inherit"],
        env: { ...process.env, CRYPTEX_WRITE_INBOX_FIXTURE: "1" },
    },
);
if (inbox.status !== 0) throw new Error("Writing the inbox fixture failed.");
run(
    "pnpm",
    [
        "exec",
        "oxfmt",
        "targets/AutofillCoreTests/Fixtures/vault.json",
        "targets/AutofillCoreTests/Fixtures/inbox.json",
    ],
    mobile,
);
